const same = (vals) => vals.every((v) => v === vals[0]);
// 'all' = in every report, 'none' = in none, 'some' = in part of them.
export const topicState = (vals) => (vals.every((v) => v) ? 'all' : vals.every((v) => !v) ? 'none' : 'some');
export const isSame = (vals) => same(vals.map((v) => (v === null ? '' : String(v))));

export function compareSummary() {
  const st = TOPICS.map((t) => topicState(t[2]));
  return {
    reports: CARDS.length,
    topics: TOPICS.length,
    core: st.filter((s) => s === 'all').length,
    missing: st.filter((s) => s === 'none').length,
    partial: st.filter((s) => s === 'some').length,
    assumptions: ASSUMPTIONS.length,
    sameAssumptions: ASSUMPTIONS.filter((a) => isSame(a[2])).length
  };
}

// Spread between the reports, as max / min - 1 (in %).
export const spread = (nums) => (Math.max(...nums) / Math.min(...nums) - 1) * 100;
